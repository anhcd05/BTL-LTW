Set-StrictMode -Version Latest
# Shared helpers for the isolated AI-recommendation demo (Compose project infosound-demo).
# Safety contract: never touches the real infosound-local project, its volumes, secrets or infosound/*:local images.
. (Join-Path $PSScriptRoot '..\..\infosound\scripts\local-runtime.ps1')

$script:RecoDemoProject = 'infosound-demo'
$script:RecoDemoBuildServices = @('tools','api','audio-worker','background-worker','web','gateway','postgres')
$script:RecoDemoPortProfiles = @{
    # Development: coexists with the real stack (3443/9443/28080).
    alternate = @{APP_HTTPS_PORT='4443'; MEDIA_HTTPS_PORT='10943'; APP_HTTP_PORT='28081'}
    # Presentation day: standard origins, only after the USER stopped the real stack.
    standard  = @{APP_HTTPS_PORT='3443'; MEDIA_HTTPS_PORT='9443'; APP_HTTP_PORT='28081'}
}

function Get-RecoDemoPaths {
    $repoRoot = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..\..'))
    $privateRoot = Join-Path $repoRoot '.runtime-private'
    $demoRoot = Join-Path $privateRoot 'reco-demo'
    return [pscustomobject]@{
        RepoRoot        = $repoRoot
        SourceRoot      = Join-Path $repoRoot 'infosound'
        RecoRoot        = Join-Path $repoRoot 'recommendation-ai'
        DemoRoot        = $demoRoot
        RuntimeFile     = Join-Path $demoRoot 'runtime.env'
        SecretsRoot     = Join-Path $demoRoot 'secrets'
        GeneratedRoot   = Join-Path $demoRoot 'generated'
        RealSecretsRoot = Join-Path $privateRoot 'local-runtime\secrets'
    }
}

function Get-RecoDemoDocker {
    $docker = Get-Command docker.exe -ErrorAction SilentlyContinue
    $dockerPath = if ($docker) { $docker.Source } else { Join-Path $env:ProgramFiles 'Docker/Docker/resources/bin/docker.exe' }
    if (!(Test-Path -LiteralPath $dockerPath -PathType Leaf)) { throw 'Docker Desktop CLI is not installed.' }
    $osType = & $dockerPath --context desktop-linux info --format '{{.OSType}}' 2>$null
    if ($LASTEXITCODE -ne 0 -or ([string]$osType).Trim() -ne 'linux') { throw 'Start Docker Desktop with its Linux engine first.' }
    return $dockerPath
}

function Test-RecoDemoRealStackRunning {
    param([Parameter(Mandatory=$true)][string]$Docker)
    $names = & $Docker --context desktop-linux ps --filter 'label=com.docker.compose.project=infosound-local' --format '{{.Names}}'
    if ($LASTEXITCODE -ne 0) { throw 'Could not query Docker for the real stack state.' }
    return [bool]($names | Where-Object { $_ })
}

function Get-RecoDemoLocalImageIds {
    param([Parameter(Mandatory=$true)][string]$Docker)
    $lines = & $Docker --context desktop-linux images --no-trunc --format '{{.Repository}}:{{.Tag}} {{.ID}}' --filter 'reference=infosound/*:local'
    if ($LASTEXITCODE -ne 0) { throw 'Could not list infosound/*:local images.' }
    return (@($lines | Where-Object { $_ }) | Sort-Object) -join "`n"
}

function Write-RecoDemoTextFile {
    param([Parameter(Mandatory=$true)][string]$Path,[Parameter(Mandatory=$true)][string]$Text)
    [IO.File]::WriteAllText($Path, $Text, (New-Object Text.UTF8Encoding($false)))
}

function Initialize-RecoDemoRuntime {
    <# Creates/refreshes ../.runtime-private/reco-demo/{runtime.env,secrets,generated}. Never prints secret values. #>
    param([ValidateSet('alternate','standard')][string]$PortMode = 'alternate')
    $paths = Get-RecoDemoPaths
    foreach ($dir in @($paths.DemoRoot, $paths.SecretsRoot, $paths.GeneratedRoot)) { New-Item -ItemType Directory -Force -Path $dir | Out-Null }
    $ports = $script:RecoDemoPortProfiles[$PortMode]
    $app = if ($ports.APP_HTTPS_PORT -eq '443') { 'https://localhost' } else { 'https://localhost:' + $ports.APP_HTTPS_PORT }
    $media = 'https://localhost:' + $ports.MEDIA_HTTPS_PORT
    $lines = @(
        '# Generated by recommendation-ai/demo/start-demo.ps1. Synthetic demo only; never the real stack.',
        'COMPOSE_PROJECT_NAME=infosound-demo',
        ('RECO_DEMO_PORT_MODE=' + $PortMode),
        'LOCAL_DEPLOYMENT_MODE=true',
        'APP_HOST=127.0.0.1',
        ('APP_ORIGIN=' + $app),
        ('LOCAL_APP_ORIGIN=' + $app),
        'LAN_APP_ORIGIN=',
        ('MEDIA_ORIGIN=' + $media),
        ('S3_PUBLIC_ENDPOINT=' + $media),
        ('APP_HTTP_PORT=' + $ports.APP_HTTP_PORT),
        ('APP_HTTPS_PORT=' + $ports.APP_HTTPS_PORT),
        ('MEDIA_HTTPS_PORT=' + $ports.MEDIA_HTTPS_PORT),
        ('SECRETS_DIR=' + $paths.SecretsRoot.Replace('\','/')),
        '# OAuth and email are disabled (oauth.json/smtp.json are {}); no external AI service.',
        'EMAIL_ENABLED=false',
        'MODERATION_AI_ENABLED=false',
        'GEMINI_API_KEY=',
        'CONVERT_LOSSY_TO_FLAC=true',
        'LOCAL_REDIS_IMAGE=redis:7.4.12-alpine',
        'LOCAL_STORAGE_IMAGE=chrislusf/seaweedfs:4.51'
    )
    Write-RecoDemoTextFile -Path $paths.RuntimeFile -Text (($lines -join "`n") + "`n")
    # TLS: reuse the project CA certificate and the localhost server certificate (SAN DNS:localhost; ports are not
    # part of the certificate). The CA private key is NOT copied.
    foreach ($name in @('ca.crt','server.crt','server.key')) {
        $target = Join-Path $paths.SecretsRoot $name
        if (!(Test-Path -LiteralPath $target)) {
            $source = Join-Path $paths.RealSecretsRoot $name
            if (!(Test-Path -LiteralPath $source -PathType Leaf)) { throw "Project TLS file $name is missing from the private local runtime." }
            Copy-Item -LiteralPath $source -Destination $target
        }
    }
    # LF copy of the PostgreSQL role bootstrap (git autocrlf leaves the working tree CRLF, which breaks bash).
    $roles = [IO.File]::ReadAllText((Join-Path $paths.SourceRoot 'infra\postgres\01-roles.sh')).Replace("`r`n","`n")
    Write-RecoDemoTextFile -Path (Join-Path $paths.GeneratedRoot '01-roles.sh') -Text $roles
    return $paths
}

function Get-RecoDemoContext {
    $paths = Get-RecoDemoPaths
    if (!(Test-Path -LiteralPath $paths.RuntimeFile -PathType Leaf)) { throw 'Demo runtime is missing. Run recommendation-ai/demo/start-demo.ps1 first.' }
    $values = Read-InfoSoundEnvironmentFile -Path $paths.RuntimeFile
    if ($values['COMPOSE_PROJECT_NAME'] -cne $script:RecoDemoProject) { throw 'Demo runtime.env must target the infosound-demo project.' }
    if (!$values['SECRETS_DIR'] -or [IO.Path]::GetFullPath($values['SECRETS_DIR']) -ne [IO.Path]::GetFullPath($paths.SecretsRoot)) { throw 'Demo SECRETS_DIR must be the reco-demo secrets directory.' }
    $values['LOCAL_NGINX_CONFIG'] = (Join-Path $paths.GeneratedRoot 'nginx.conf').Replace('\','/')
    $values['RECO_DEMO_ROLES_SCRIPT'] = (Join-Path $paths.GeneratedRoot '01-roles.sh').Replace('\','/')
    $docker = Get-RecoDemoDocker
    return [pscustomobject]@{
        SourceRoot = $paths.SourceRoot; RuntimeFile = $paths.RuntimeFile; RuntimeRoot = $paths.DemoRoot
        SecretsRoot = $paths.SecretsRoot; Values = $values; Docker = $docker; Paths = $paths
    }
}

function Invoke-RecoDemoCompose {
    param([Parameter(Mandatory=$true)]$Context,[Parameter(Mandatory=$true)][string[]]$Arguments)
    $root = $Context.SourceRoot
    $compose = @('compose','--project-directory',$root,'--project-name',$script:RecoDemoProject,
        '--env-file',(Join-Path $root 'images.env'),'--env-file',$Context.RuntimeFile,
        '-f',(Join-Path $root 'compose.yaml'),'-f',(Join-Path $root 'compose.lab.yaml'),
        '-f',(Join-Path $root 'compose.local.yaml'),'-f',(Join-Path $root 'compose.reco-demo.yaml'))
    Invoke-InfoSoundLocalDocker -Context $Context -Arguments ($compose + $Arguments)
}

function Invoke-RecoDemoComposeOutput {
    <# Same as Invoke-RecoDemoCompose, returning trimmed stdout lines to the caller. #>
    param([Parameter(Mandatory=$true)]$Context,[Parameter(Mandatory=$true)][string[]]$Arguments)
    return @(Invoke-RecoDemoCompose -Context $Context -Arguments $Arguments | ForEach-Object { ([string]$_).Trim() } | Where-Object { $_ })
}

function New-RecoDemoBuildSource {
    <# LF snapshot of the CURRENT working tree (tracked + untracked, .gitignore respected) for docker builds.
       git autocrlf=true leaves the checkout CRLF, which breaks e.g. the web locale hash check. The working tree is
       not modified: files are hashed into a throw-away index, and the resulting tree (blobs are stored LF) is
       archived with autocrlf disabled into a temp directory outside the repository. #>
    $paths = Get-RecoDemoPaths
    $git = (Get-Command git.exe -ErrorAction Stop).Source
    $stage = Join-Path ([IO.Path]::GetTempPath()) 'infosound-reco-build'
    $index = Join-Path ([IO.Path]::GetTempPath()) ('infosound-reco-index-' + [guid]::NewGuid().ToString('N'))
    $tar = $index + '.tar'
    $previousIndex = $env:GIT_INDEX_FILE
    # Start from a copy of the real index so tracked-but-ignored paths (e.g. infosound/scripts/) are kept.
    $realIndex = (& $git -C $paths.RepoRoot rev-parse --path-format=absolute --git-path index).Trim()
    Copy-Item -LiteralPath $realIndex -Destination $index
    try {
        $env:GIT_INDEX_FILE = $index
        & $git -C $paths.RepoRoot -c core.safecrlf=false add -A -- infosound comment-moderation recommendation-ai 2>$null
        if ($LASTEXITCODE -ne 0) { throw 'git add into the temporary index failed.' }
        $tree = (& $git -C $paths.RepoRoot write-tree).Trim()
        if ($LASTEXITCODE -ne 0 -or $tree -notmatch '^[0-9a-f]{40}$') { throw 'git write-tree failed.' }
    } finally {
        $env:GIT_INDEX_FILE = $previousIndex
        Remove-Item -LiteralPath $index -Force -ErrorAction SilentlyContinue
    }
    & $git -C $paths.RepoRoot -c core.autocrlf=false -c core.eol=lf archive --format=tar -o $tar $tree infosound comment-moderation recommendation-ai
    if ($LASTEXITCODE -ne 0) { throw 'git archive of the LF build snapshot failed.' }
    if (Test-Path -LiteralPath $stage) { Remove-Item -LiteralPath $stage -Recurse -Force }
    New-Item -ItemType Directory -Path $stage | Out-Null
    & "$env:SystemRoot\System32\tar.exe" -xf $tar -C $stage
    if ($LASTEXITCODE -ne 0) { throw 'Extracting the LF build snapshot failed.' }
    Remove-Item -LiteralPath $tar -Force
    Write-Host ("LF build snapshot of the working tree: tree {0} -> {1}" -f $tree, $stage)
    return (Join-Path $stage 'infosound')
}

function Assert-RecoDemoPortsUsable {
    param([Parameter(Mandatory=$true)]$Context)
    if ($Context.Values['RECO_DEMO_PORT_MODE'] -eq 'standard' -and (Test-RecoDemoRealStackRunning -Docker $Context.Docker)) {
        throw 'Standard ports 3443/9443 belong to the running real stack. Stop it yourself first (infosound\scripts\stop-local.ps1); this script never stops it.'
    }
}
